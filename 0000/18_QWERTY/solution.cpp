#include <iostream>
#include <string>
#include <cctype>

using namespace std;

int main()
{
    char input[68] = {' ', '`', '!', '@', '#', '$', '%', '^', '&', '*', '(', ')', '_', '+', '-', '=', 'a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i', 'j', 'k', 'l', 'm', 'n', 'o', 'p', 'q', 'r', 's', 't', 'u', 'v', 'w', 'x', 'y', 'z', '{', '}', '[', ']', '|', '\\', ';', '\'', '"', ':', ',', '.', '/', '<', '>', '?', '1', '2', '3', '4', '5', '6', '7', '8', '9', '0'};
    char output[68] = {' ', '!', '@', '#', '$', '%', '^', '&', '*', '(', ')', '_', '+', '+', '=', '=', 's', 'n', 'v', 'f', 'r', 'g', 'h', 'j', 'o', 'k', 'l', ';', ',', 'm', 'p', '[', 'w', 't', 'd', 'y', 'i', 'b', 'e', 'c', 'u', 'x', '}', '|', ']', '\\', '|', '\\', '\'', '\'', '"', '"', '.', '/', '/', '>', '?', '?', '2', '3', '4', '5', '6', '7', '8', '9', '0', '-'};

    string a;

    while(getline(cin, a))
    {
        for(int i = 0; i < a.length(); i++)
        {
            char c = a[i];
            c = tolower(c);
            for(int j = 0; j < 68; j++)
            {
                if(c == input[j])
                {
                    cout << output[j];
                }
            }
        }
        cout << endl;
    }
    return 0;
}
